import hashlib
import json
import tempfile
import unittest
from pathlib import Path

from verifier.profile_engine import create_profile_receipt, verify_profile_package


MANIFEST = {
    "manifest_version": "0.1",
    "profile_id": "org.example.profile.demo",
    "profile_version": "0.1.0",
    "profile_name": "Demo Profile",
    "profile_status": "draft",
    "core_compatibility": {"min_version": "0.1", "max_version": "0.1"},
    "specification_uri": "https://example.org/demo/spec",
    "evidence_schema_uri": "https://example.org/demo/schema",
    "evidence_media_type": "application/json",
    "verification": {
        "required_checks": [
            "core_integrity",
            "profile_package_integrity",
            "manifest_validation",
            "profile_schema_validation"
        ],
        "result_model": "CORD-PROFILE-RESULT-0.1"
    }
}
EVIDENCE_SCHEMA = {
    "$schema": "https://json-schema.org/draft/2020-12/schema",
    "type": "object",
    "additionalProperties": False,
    "required": ["record_id", "claim"],
    "properties": {
        "record_id": {"type": "string", "minLength": 1},
        "claim": {"type": "string", "minLength": 1}
    }
}
EVIDENCE = {"record_id": "demo-001", "claim": "Example claim"}
BUNDLE = {
    "spec_version": "0.1",
    "model_id": "demo-model",
    "timestamp": "2026-03-06T12:00:00Z",
    "policy_id": "cord-output-v0.1",
    "input_hash": "1" * 64,
    "output_hash": "2" * 64,
}
NOW = "2026-03-06T12:00:05Z"


def write_json(path: Path, value: dict) -> bytes:
    raw = (json.dumps(value, ensure_ascii=False, indent=2) + "\n").encode()
    path.write_bytes(raw)
    return raw


class ProfileEngineTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.package = self.root / "package"
        self.registry = self.root / "registry"
        self.profile_dir = self.registry / "profiles" / "demo"
        self.package.mkdir()
        self.profile_dir.mkdir(parents=True)
        write_json(self.package / "bundle.json", BUNDLE)
        # Core receipt hashes are generated by the existing Core implementation.
        from verifier.verify import create_receipt
        create_receipt(self.package / "bundle.json", self.package / "receipt.json", NOW)
        self.manifest_raw = write_json(self.profile_dir / "manifest.json", MANIFEST)
        write_json(self.profile_dir / "evidence.schema.json", EVIDENCE_SCHEMA)
        write_json(self.package / "profile-manifest.json", MANIFEST)
        write_json(self.package / "profile-evidence.json", EVIDENCE)
        write_json(
            self.registry / "registry.json",
            {
                "registry_version": "0.1",
                "profiles": {
                    MANIFEST["profile_id"]: {
                        MANIFEST["profile_version"]: {
                            "manifest_path": "profiles/demo/manifest.json",
                            "evidence_schema_path": "profiles/demo/evidence.schema.json"
                        }
                    }
                }
            }
        )
        create_profile_receipt(
            self.package / "profile-manifest.json",
            self.package / "profile-evidence.json",
            self.package / "profile-receipt.json",
            created_at=NOW,
        )

    def tearDown(self):
        self.temp.cleanup()

    def test_valid_profile_package_passes(self):
        result = verify_profile_package(self.package, self.registry)
        self.assertEqual(result["status"], "PASS", result)
        self.assertEqual(result["checks"]["core_integrity"]["status"], "PASS")
        self.assertEqual(result["checks"]["profile_validation"]["status"], "PASS")

    def test_evidence_tampering_fails(self):
        write_json(self.package / "profile-evidence.json", {"record_id": "changed", "claim": "changed"})
        result = verify_profile_package(self.package, self.registry)
        self.assertEqual(result["status"], "FAIL")
        self.assertIn("hash mismatch", result["error"])

    def test_unregistered_profile_is_unsupported(self):
        manifest = dict(MANIFEST, profile_id="org.example.profile.unknown")
        write_json(self.package / "profile-manifest.json", manifest)
        create_profile_receipt(
            self.package / "profile-manifest.json",
            self.package / "profile-evidence.json",
            self.package / "profile-receipt.json",
            created_at=NOW,
        )
        result = verify_profile_package(self.package, self.registry)
        self.assertEqual(result["status"], "UNSUPPORTED")

    def test_pinned_manifest_substitution_fails(self):
        manifest = dict(MANIFEST, profile_name="Substituted")
        write_json(self.package / "profile-manifest.json", manifest)
        create_profile_receipt(
            self.package / "profile-manifest.json",
            self.package / "profile-evidence.json",
            self.package / "profile-receipt.json",
            created_at=NOW,
        )
        result = verify_profile_package(self.package, self.registry)
        self.assertEqual(result["status"], "FAIL")
        self.assertIn("pinned manifest", result["error"])

    def test_profile_schema_violation_fails(self):
        write_json(self.package / "profile-evidence.json", {"record_id": "missing-claim"})
        create_profile_receipt(
            self.package / "profile-manifest.json",
            self.package / "profile-evidence.json",
            self.package / "profile-receipt.json",
            created_at=NOW,
        )
        result = verify_profile_package(self.package, self.registry)
        self.assertEqual(result["status"], "FAIL")
        self.assertIn("schema validation failed", result["error"])

    def test_registry_path_traversal_is_rejected(self):
        write_json(
            self.registry / "registry.json",
            {
                "registry_version": "0.1",
                "profiles": {
                    MANIFEST["profile_id"]: {
                        MANIFEST["profile_version"]: {
                            "manifest_path": "../outside.json",
                            "evidence_schema_path": "profiles/demo/evidence.schema.json"
                        }
                    }
                }
            }
        )
        result = verify_profile_package(self.package, self.registry)
        self.assertEqual(result["status"], "FAIL")
        self.assertIn("escapes", result["error"])


if __name__ == "__main__":
    unittest.main()
